// The cache namespace includes the registration scope: other apps and other
// Horar paths on a shared host must retain their own offline files.
export function serviceWorkerSource(precache,buildId){
  return `// Generated by postbuild.mjs. Calculations and records stay on-device.
const PREFIX='horary-pwa:'+self.registration.scope+':';
const CACHE=PREFIX+${JSON.stringify(buildId)};
const PRECACHE=${JSON.stringify(precache)};
self.addEventListener('install',event=>event.waitUntil(
  caches.open(CACHE).then(cache=>cache.addAll(PRECACHE)).then(()=>self.skipWaiting())
));
self.addEventListener('activate',event=>event.waitUntil(
  caches.keys().then(keys=>Promise.all(
    keys.filter(key=>key.startsWith(PREFIX)&&key!==CACHE).map(key=>caches.delete(key))
  )).then(()=>self.clients.claim())
));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==self.location.origin||
    !url.href.startsWith(self.registration.scope))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const cached=await cache.match(event.request);
    if(cached)return cached;
    try{return await fetch(event.request);}
    catch{
      // HTML is a fallback only for pages, never for WASM, scripts or JSON.
      if(event.request.mode==='navigate'){
        const shell=await cache.match(new URL('./index.html',self.registration.scope).href);
        if(shell)return shell;
      }
      return Response.error();
    }
  })());
});
`;
}
